"""Generate the 1290, 312 and V72 bounded circuit models and reference reports."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path

from characterize import characterize_case

HERE = Path(__file__).resolve().parent
CASES = (
    *((f"1290", r, impedance, extra, .4)
      for impedance in (1, 2) for r, extra in ((1200, 0), (120, 0), (120, 1))),
    *((f"312", r, ratio, 0, .35)
      for ratio in (3, 1) for r in (16000, 1800, 1)),
    ("v72", 4000, 1, 0, .8),
)


def run(case, executable):
    unit, resistance, switch, extra, scale = case
    netlist = (HERE / f"{unit}.cir").read_text().replace("EXTRA=0", f"EXTRA={extra}")
    entry, report = characterize_case(executable, netlist, resistance, switch,
                                      band=(12, 36000), scale=scale,
                                      levels=(-65, -45, -30, -25) if unit == "v72" else (-65, -45, -30))
    report.update(model=unit, gain_stage_inserted=bool(extra), switch_position=switch,
                  internal_output_scaling=scale)
    return entry, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ngspice", default="ngspice")
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--jobs", type=int, choices=range(1, 9), default=4)
    args = parser.parse_args()
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        entries, report = zip(*pool.map(lambda case: run(case, args.ngspice), CASES))
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("// Generated by spice/characterize_extra.py\n#pragma once\n"
                           "#include \"TypeDModel.h\"\nnamespace tg {\n"
                           "inline constexpr Model extraModels[] = {\n"
                           + ",\n".join(entries) + "\n};\n}\n")
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
